const originalMarkup = new Map();
const originalText = new Map();
const translatableSelectors =
  "title, .hero-title, .eyebrow, .hero-sub, .home-button, .view-btn, .figure-hint, .region-chip, .h1, .h2, .p, .workout-jump-links a, .workout-name";

function normalizedText(element) {
  return (element.textContent || "").replace(/\s+/g, " ").trim();
}

function readSavedLanguage() {
  try {
    return localStorage.getItem("flex-gym-language") || "en";
  } catch (error) {
    console.error("Unable to read the saved language preference.", error);
    return "en";
  }
}

function applyLanguage(language) {
  const isArabic = language === "ar";
  document.documentElement.lang = language;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";

  document.querySelectorAll(translatableSelectors).forEach((element) => {
    if (!originalMarkup.has(element)) {
      originalMarkup.set(element, element.innerHTML);
    }

    const englishText = normalizedText(element);
    if (!isArabic) {
      element.innerHTML = originalMarkup.get(element);
      return;
    }

    const translation =
      isArabic && englishText === "Back" && element.classList.contains("view-btn")
        ? "الخلف"
        : translations[englishText];
    if (translation) {
      element.innerHTML = translation;
    }
  });

  document.querySelectorAll("[aria-label]").forEach((element) => {
    if (!element.dataset.englishAriaLabel) {
      element.dataset.englishAriaLabel = element.getAttribute("aria-label");
    }
    const englishLabel = element.dataset.englishAriaLabel;
    element.setAttribute(
      "aria-label",
      isArabic ? translations[englishLabel] || englishLabel : englishLabel,
    );
  });

  document.querySelectorAll(".socials a").forEach((link) => {
    link.childNodes.forEach((node) => {
      if (node.nodeType !== Node.TEXT_NODE) {
        return;
      }
      if (!originalText.has(node)) {
        originalText.set(node, node.nodeValue);
      }
      const englishText = originalText.get(node).trim();
      node.nodeValue = isArabic
        ? originalText.get(node).replace(englishText, translations[englishText] || englishText)
        : originalText.get(node);
    });
  });

  const footer = document.querySelector(".footer-text");
  if (footer) {
    if (!footer.dataset.englishMarkup) {
      footer.dataset.englishMarkup = footer.innerHTML;
    }
    footer.innerHTML = isArabic
      ? 'تصميم وتطوير <span class="footer-divider">|</span> <a class="footer-link" href="https://www.instagram.com/_.ramn.__/" target="_blank" rel="noopener noreferrer">RAMIN</a>'
      : footer.dataset.englishMarkup;
  }

  document.querySelectorAll(".language-toggle").forEach((button) => {
    const isSelected = button.dataset.language === language;
    button.classList.toggle("is-active", isSelected);
    button.setAttribute("aria-pressed", String(isSelected));
  });
  try {
    localStorage.setItem("flex-gym-language", language);
  } catch (error) {
    console.error("Unable to save the language preference.", error);
  }
}

const siteHeader = document.querySelector(".site-header");
if (siteHeader) {
  const languageSwitch = document.createElement("div");
  languageSwitch.className = "language-switch-row";
  languageSwitch.setAttribute("role", "group");
  languageSwitch.setAttribute("aria-label", "Language");
  ["en", "ar"].forEach((language) => {
    const button = document.createElement("button");
    button.className = "language-toggle";
    button.type = "button";
    button.dataset.language = language;
    button.textContent = language.toUpperCase();
    button.setAttribute(
      "aria-label",
      language === "en" ? "English" : "العربية",
    );
    button.addEventListener("click", () => applyLanguage(language));
    languageSwitch.append(button);
  });
  siteHeader.insertAdjacentElement("afterend", languageSwitch);
  applyLanguage(readSavedLanguage());
}
